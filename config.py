# 反向查詢：小族群名 → 主族群名
_SECTOR_TO_META = {
    sub: meta
    for meta, subs in META_SECTORS.items()
    for sub in subs
}


def get_meta_sector(sector_name: str) -> str | None:
    """回傳該族群所屬的主族群名，不在任何主族群則回傳 None。"""
    return _SECTOR_TO_META.get(sector_name)


def classify_sector(sector_name: str) -> str:
    """根據族群名稱返回所屬分組。"""
    for group_name, keywords in SECTOR_GROUPS[:-1]:  # 排除最後的「其他」
        for kw in keywords:
            if kw in sector_name:
                return group_name
    return "其他電子"
