def is_trading_day(date_str: str) -> bool:
    """判斷某日是否為交易日（非週末、非國定假日）。"""
    import datetime
    dt = datetime.date.fromisoformat(date_str)
    if dt.weekday() >= 5:  # 週六/日
        return False
    return date_str not in TAIWAN_HOLIDAYS


